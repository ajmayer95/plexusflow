"""Per-stage config + path resolution.

A "stage" is a self-contained dataset — a specific embryo at a specific
somite count — living in its own top-level folder (e.g. `PlexusFlow21S/`).
All pipeline stages resolve inputs/outputs relative to this folder.

Downsampling model
------------------
The pipeline supports two independent downsample factors, both explicit:

  * ``stitch_downsample``  — display-only downsample used during the
    napari stitcher (memory savings while dragging tiles). The saved
    positions.json is ALWAYS in FULL-RES world coordinates (the stitcher
    multiplies back), so this factor doesn't leak into any downstream
    stage.

  * ``fuse_downsample`` — used when feathering per-tile images into the
    single stitched image. Output resolution = full_res / fuse_downsample.
    All downstream artifacts (mask, graph) live in this fused coordinate
    frame; graph node x/y are in fused pixel coordinates.

To convert graph coords back to full-res image coords, multiply by
``fuse_downsample``. This factor is stamped into `provenance.json` next
to every artifact for traceability.

Folder layout (per stage folder)
--------------------------------

    PlexusFlow21S/
    ├── plexusflow.yaml           optional config overrides
    ├── tiles/
    │   ├── std_clahe/            per-tile std+CLAHE tiff (vid{N}_std_clahe.tif)
    │   ├── maxmed/               per-tile MaxMed tiff    (vid{N}_maxmed.tif)
    │   └── probs/                per-tile ilastik output (vid{N}_maxmed_probs.h5)
    ├── stitch/
    │   ├── positions.json        napari-stitcher output (FULL-RES coords)
    │   └── provenance.json       stamped params
    ├── fuse/
    │   ├── intensity.tif         feathered StdFilter
    │   ├── maxmed.tif            feathered MaxMed
    │   ├── probs_linear.tif      per-tile probs, arithmetic mean
    │   ├── probs_logit.tif       per-tile probs, logit-space mean
    │   └── provenance.json       stamped params
    ├── mask/
    │   ├── mask.tif              binary 0/255 vessel mask
    │   ├── mask.json             threshold-tool sidecar
    │   └── provenance.json
    └── graph/
        ├── graph.gpickle
        └── provenance.json
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Optional, Union
import json
import yaml


@dataclass
class StageConfig:
    """Resolves all paths for one stage dataset."""

    root: Path
    # Tile input directories + patterns
    tile_std_clahe_pattern: str = "vid{vid}_std_clahe.tif"
    tile_maxmed_pattern: str = "vid{vid}_maxmed.tif"
    tile_bandpass_pattern: str = "vid{vid}_bandpass.tif"
    tile_probs_pattern: str = "vid{vid}_maxmed_probs.h5"
    # Raw video: each tile is a FOLDER of frame TIFFs (~2000 frames × ~1 MB).
    # The pattern must contain {vid} to locate the tile-specific folder.
    raw_video_dir_pattern: str = "10x 250fps loc{vid}_*"   # folder glob
    raw_video_frame_glob: str = "*.tif"                     # frames inside
    raw_fps: float = 250.0                                   # sampling rate
    # Optional external tile source dirs (if not under the stage folder).
    # Useful during migration from PerTileFlow layouts.
    external_std_clahe_dir: Optional[Path] = None
    external_maxmed_dir: Optional[Path] = None
    external_probs_dir: Optional[Path] = None
    external_raw_video_dir: Optional[Path] = None
    # Downsample factors
    stitch_downsample: int = 2      # napari display; positions saved at FULL RES
    fuse_downsample: int = 2         # applied to feather output resolution
    # Feather params
    fuse_feather_alpha: float = 0.7  # feather kernel sharpness (weight = dist^alpha)
    probs_channel: int = 0            # which ilastik output channel is vessel (0 or 1)
    # Mask defaults
    mask_default_threshold: float = 0.5
    mask_default_low: float = 0.25
    mask_default_min_size: int = 100
    mask_default_close_radius: int = 1
    # Vectorization params (net3)
    vectorize_min_feature_size: int = 100
    vectorize_prune_order: int = 3
    # Fill mask holes of area ≤ N pixels before feeding net3.  Applied to
    # a temp copy so mask.tif on disk is preserved.  Set 0 to disable.
    vectorize_fill_holes: int = 20
    # Close 1-px background slits (3×3-cross closing) on the temp copy before net3 — see vectorize._prep_mask_for_net3.
    vectorize_close_slits: bool = True
    # Downsampled per-tile videos for viewer playback.  When
    # ``videos_realtime/`` exists under the stage root, the viewer uses it
    # as the display video source (fast enough for realtime playback) and
    # keeps ``raw/`` as the OF-computation source.  Generated by
    # ``plexusflow downsample-videos``.
    videos_realtime_spatial_ds: int = 2
    # 250 fps raw → 62.5 fps playback at ×4 (matches display refresh).
    videos_realtime_temporal_ds: int = 4
    # Flow analysis.  Heart-rate search band (Hz) for per-tile f0 and its sanity check.
    f0_min_hz: float = 0.8
    f0_max_hz: float = 3.5
    # Optical-flow frame spacing: 1, an integer, or "auto" (per-vessel: pilot at dt=1, then
    # dt = clip(round(of_target_disp_px / peak displacement), 1, of_dt_max)).
    of_dt: Union[int, str] = 1
    of_dt_max: int = 12
    of_target_disp_px: float = 1.0
    # Per-tile override of of_dt, e.g. {30: 12, 31: 12} (yaml keys may be ints or strings).
    of_dt_by_tile: dict = field(default_factory=dict)
    # Tiles never used for flow measurement (e.g. no detectable flow); their stored measurements are dropped on analyze.
    exclude_tiles: list = field(default_factory=list)

    # ----- resolved paths (populated in __post_init__) -----
    tiles_std_clahe_dir: Path = field(init=False)
    tiles_maxmed_dir: Path = field(init=False)
    tiles_bandpass_dir: Path = field(init=False)
    tiles_probs_dir: Path = field(init=False)
    raw_video_dir: Path = field(init=False)
    positions_path: Path = field(init=False)
    fuse_intensity_path: Path = field(init=False)
    fuse_maxmed_path: Path = field(init=False)
    fuse_bandpass_path: Path = field(init=False)
    fuse_probs_linear_path: Path = field(init=False)
    fuse_probs_logit_path: Path = field(init=False)
    mask_path: Path = field(init=False)
    graph_path: Path = field(init=False)
    graph_vessels_path: Path = field(init=False)
    graph_piv_path: Path = field(init=False)
    graph_normalized_path: Path = field(init=False)
    videos_realtime_dir: Path = field(init=False)

    def __post_init__(self):
        r = Path(self.root).expanduser().resolve()
        self.root = r
        self.tiles_std_clahe_dir = (Path(self.external_std_clahe_dir).expanduser()
                                     if self.external_std_clahe_dir else r / "tiles" / "std_clahe")
        self.tiles_maxmed_dir    = (Path(self.external_maxmed_dir).expanduser()
                                     if self.external_maxmed_dir else r / "tiles" / "maxmed")
        self.tiles_bandpass_dir  = r / "tiles" / "bandpass"
        self.tiles_probs_dir     = (Path(self.external_probs_dir).expanduser()
                                     if self.external_probs_dir else r / "tiles" / "probs")
        self.raw_video_dir       = (Path(self.external_raw_video_dir).expanduser()
                                     if self.external_raw_video_dir else r / "raw")
        self.positions_path       = r / "stitch" / "positions.json"
        self.fuse_intensity_path  = r / "fuse"   / "intensity.tif"
        self.fuse_maxmed_path     = r / "fuse"   / "maxmed.tif"
        self.fuse_bandpass_path   = r / "fuse"   / "bandpass.tif"
        self.fuse_probs_linear_path = r / "fuse" / "probs_linear.tif"
        self.fuse_probs_logit_path  = r / "fuse" / "probs_logit.tif"
        self.mask_path            = r / "mask"   / "mask.tif"
        self.graph_path           = r / "graph"  / "graph.gpickle"
        self.graph_vessels_path   = r / "graph"  / "graph_vessels.gpickle"
        self.graph_piv_path       = r / "graph"  / "graph_vessels_piv.gpickle"
        self.graph_normalized_path = r / "graph"  / "graph_vessels_piv_normalized.gpickle"
        self.videos_realtime_dir  = r / "videos_realtime"

    @classmethod
    def load(cls, root: str | Path) -> "StageConfig":
        """Load config from `root/plexusflow.yaml` if present, else defaults."""
        root = Path(root).expanduser().resolve()
        cfg_path = root / "plexusflow.yaml"
        overrides = {}
        if cfg_path.exists():
            with open(cfg_path) as f:
                overrides = yaml.safe_load(f) or {}
        # Only pass known fields
        valid = {f.name for f in cls.__dataclass_fields__.values() if f.init}
        overrides = {k: v for k, v in overrides.items() if k in valid}
        return cls(root=root, **overrides)

    def ensure_dirs(self) -> None:
        """Create per-stage output dirs on demand."""
        for p in (self.positions_path, self.fuse_intensity_path,
                   self.mask_path, self.graph_path):
            p.parent.mkdir(parents=True, exist_ok=True)

    def discover_tile_ids(self, source: str = "std_clahe") -> list[int]:
        """Auto-discover tile IDs from filenames in one of the tile dirs."""
        d = {"std_clahe": self.tiles_std_clahe_dir,
             "maxmed":    self.tiles_maxmed_dir,
             "probs":     self.tiles_probs_dir}[source]
        pat = {"std_clahe": self.tile_std_clahe_pattern,
               "maxmed":    self.tile_maxmed_pattern,
               "probs":     self.tile_probs_pattern}[source]
        prefix, suffix = pat.split("{vid}", 1)
        ids: list[int] = []
        for f in d.glob(f"{prefix}*{suffix}"):
            s = f.name[len(prefix): len(f.name) - len(suffix)]
            try: ids.append(int(s))
            except ValueError: pass
        return sorted(ids)

    def raw_tile_folder(self, tile_id: int) -> Path:
        """Return the raw-video folder for one tile, or raise if not found.
        Uses `raw_video_dir_pattern` (with {vid} substituted) as a glob."""
        pat = self.raw_video_dir_pattern.format(vid=tile_id)
        hits = sorted(self.raw_video_dir.glob(pat))
        if not hits:
            raise FileNotFoundError(
                f'no raw tile folder matching {pat!r} in {self.raw_video_dir}')
        if len(hits) > 1:
            raise RuntimeError(f'ambiguous raw tile match for {pat!r}: {[h.name for h in hits]}')
        return hits[0]

    def raw_tile_frames(self, tile_id: int) -> list[Path]:
        """Return sorted list of frame paths for one raw tile."""
        return sorted(self.raw_tile_folder(tile_id).glob(self.raw_video_frame_glob))

    def discover_raw_tile_ids(self) -> list[int]:
        """Auto-discover raw tile IDs from folder names."""
        if not self.raw_video_dir.exists():
            return []
        prefix, suffix = self.raw_video_dir_pattern.split("{vid}", 1)
        # suffix may contain wildcards like '_*' — strip trailing '*' for parsing
        suffix_lit = suffix.rstrip("*")
        ids: list[int] = []
        for d in self.raw_video_dir.iterdir():
            if not d.is_dir(): continue
            n = d.name
            if not n.startswith(prefix): continue
            rest = n[len(prefix):]
            # Take digits at start of `rest` up to the suffix literal
            i = 0
            while i < len(rest) and rest[i].isdigit(): i += 1
            if i == 0: continue
            if suffix_lit and not rest[i:].startswith(suffix_lit): continue
            try: ids.append(int(rest[:i]))
            except ValueError: pass
        return sorted(ids)

    def write_provenance(self, stage: str, extra: Optional[dict] = None) -> Path:
        """Stamp a provenance.json next to the stage's outputs.

        Records the config values used AND the effective downsample factors
        so downstream stages can rescale coordinates correctly."""
        stage_dir = {
            "stitch":        self.positions_path.parent,
            "fuse":          self.fuse_intensity_path.parent,
            "mask":          self.mask_path.parent,
            "graph":         self.graph_path.parent,
            "graph_vessels": self.graph_vessels_path.parent,
            "graph_piv":     self.graph_piv_path.parent,
        }[stage]
        stage_dir.mkdir(parents=True, exist_ok=True)
        p = stage_dir / "provenance.json"
        blob = {
            "stage": stage,
            "root": str(self.root),
            "stitch_downsample": self.stitch_downsample,
            "fuse_downsample":   self.fuse_downsample,
            "fuse_feather_alpha": self.fuse_feather_alpha,
            "probs_channel":     self.probs_channel,
        }
        if extra:
            blob.update(extra)
        p.write_text(json.dumps(blob, indent=2))
        return p

    def summary(self) -> str:
        lines = [f"StageConfig(root={self.root})",
                 f"  stitch_downsample={self.stitch_downsample}  fuse_downsample={self.fuse_downsample}",
                 "  paths:"]
        for label, p in [
            ("raw videos      ", self.raw_video_dir),
            ("std_clahe tiles ", self.tiles_std_clahe_dir),
            ("maxmed tiles    ", self.tiles_maxmed_dir),
            ("probs tiles     ", self.tiles_probs_dir),
            ("positions       ", self.positions_path),
            ("fuse/intensity  ", self.fuse_intensity_path),
            ("fuse/maxmed     ", self.fuse_maxmed_path),
            ("fuse/probs_lin  ", self.fuse_probs_linear_path),
            ("fuse/probs_logit", self.fuse_probs_logit_path),
            ("mask            ", self.mask_path),
            ("graph           ", self.graph_path),
        ]:
            marker = "✓" if p.exists() else " "
            lines.append(f"    {marker} {label}  {p}")
        return "\n".join(lines)
